#!/usr/bin/env python3
"""Embed assets/states/State_Name_AB.svg drawings in an offline report catalog."""
import argparse
import base64
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET


def build(repo):
    states, names, codes = [], set(), set()
    for path in sorted((Path(repo) / 'assets/states').glob('*.svg')):
        match = re.fullmatch(r'(.+)_([A-Z]{2})', path.stem)
        if not match:
            raise ValueError('Expected State_Name_AB.svg: ' + path.name)
        name, code = match.groups()
        name = name.replace('_', ' ')
        key = re.sub(r'[^a-z]', '', name.lower())
        if key in names or code in codes:
            raise ValueError('Duplicate state name or code: ' + path.name)
        raw = path.read_bytes()
        root = ET.fromstring(raw)
        if root.tag != '{http://www.w3.org/2000/svg}svg':
            raise ValueError('Expected SVG: ' + path.name)
        for node in root.iter():
            if node.tag.rsplit('}', 1)[-1].lower() in ('script', 'foreignobject'):
                raise ValueError('Active content in ' + path.name)
            for attribute, value in node.attrib.items():
                if attribute.lower().startswith('on') or (attribute.rsplit('}', 1)[-1] == 'href' and not value.startswith('#')):
                    raise ValueError('Active or external reference in ' + path.name)
        names.add(key)
        codes.add(code)
        states.append({'name': name, 'code': code,
                       'src': 'data:image/svg+xml;base64,' + base64.b64encode(raw).decode('ascii')})
    if not states:
        raise ValueError('No drawings found in assets/states; add State_Name_AB.svg files first.')
    payload = json.dumps(states, ensure_ascii=True, separators=(',', ':'))
    return ('// Generated by scripts/build_state_assets.py; edit the SVG sources.\n'
            'globalThis.WINGS_STATE_ARTWORK = ' + payload + ';\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = args.repo / 'assets/states/state-artwork.js'
    try:
        expected = build(args.repo)
        if args.check:
            if not target.is_file() or target.read_bytes() != expected.encode('utf-8'):
                parser.exit(1, 'State artwork catalog is out of date. Run python scripts/build_state_assets.py.\n')
        else:
            target.write_text(expected, encoding='utf-8')
    except (OSError, ValueError, ET.ParseError) as error:
        parser.exit(1, str(error) + '\n')
    print('PASS: offline state artwork catalog matches SVG sources.')


if __name__ == '__main__':
    main()
