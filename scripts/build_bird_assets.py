#!/usr/bin/env python3
"""Build the offline host-artwork catalog from assets/birds/*.svg."""
import argparse
import base64
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET


def build(repo):
    birds = []
    for path in sorted((repo / 'assets/birds').glob('*.svg')):
        raw = path.read_bytes()
        root = ET.fromstring(raw)
        if root.tag != '{http://www.w3.org/2000/svg}svg':
            raise ValueError('Expected SVG: ' + path.name)
        for node in root.iter():
            if node.tag.rsplit('}', 1)[-1].lower() in ('script', 'foreignobject'):
                raise ValueError('Active content in ' + path.name)
            for key, value in node.attrib.items():
                if key.lower().startswith('on') or (key.rsplit('}', 1)[-1] == 'href' and not value.startswith('#')):
                    raise ValueError('Active or external reference in ' + path.name)
        match = re.fullmatch(r'(.+)_([A-Z]{4})', path.stem)
        name, code = match.groups() if match else (path.stem, '')
        birds.append({'name': name.replace('_', ' '), 'code': code,
                      'src': 'data:image/svg+xml;base64,' + base64.b64encode(raw).decode('ascii')})
    if not birds:
        raise ValueError('No bird drawings found')
    payload = json.dumps(birds, ensure_ascii=True, separators=(',', ':'))
    return '// Generated by scripts/build_bird_assets.py; edit the SVG sources.\n' + 'globalThis.WINGS_HOST_ARTWORK = ' + payload + ';\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = args.repo / 'assets/birds/host-artwork.js'
    expected = build(args.repo)
    if args.check:
        if not target.is_file() or target.read_bytes() != expected.encode('utf-8'):
            parser.exit(1, 'Bird artwork catalog is out of date. Run python scripts/build_bird_assets.py.\n')
    else:
        target.write_text(expected, encoding='utf-8')
    print('PASS: offline bird artwork catalog matches SVG sources.')


if __name__ == '__main__':
    main()
